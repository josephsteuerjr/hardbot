import pytest

from comment_view import newest_first


@pytest.mark.parametrize("source,expected", [
    (None, []),
    ("Офисный текст\nвторая строка", ["Офисный текст\nвторая строка"]),
    ("05.10.2026 10:00 · Сотрудник: старая\n06.10.2026 10:00 · Сотрудник: новая",
     ["06.10.2026 10:00 · Сотрудник: новая", "05.10.2026 10:00 · Сотрудник: старая"]),
    ("06.10.2026 10:00 · Сотрудник: первая\nпродолжение\n06.10.2026 10:00 · Сотрудник: вторая\nещё строка",
     ["06.10.2026 10:00 · Сотрудник: вторая\nещё строка", "06.10.2026 10:00 · Сотрудник: первая\nпродолжение"]),
    ("Офис\r\nещё\r\n31.12.2025 10:00 · А: старая\r\n01.01.2026 09:00 · Б: новая",
     ["01.01.2026 09:00 · Б: новая", "31.12.2025 10:00 · А: старая", "Офис\r\nещё"]),
    ("06.10.2026 10:00 · Сотрудник: новая\n01.10.2026 10:00 · Сотрудник: старая",
     ["06.10.2026 10:00 · Сотрудник: новая", "01.10.2026 10:00 · Сотрудник: старая"]),
    ("31.02.2026 12:00 · А: не дата\n12.10.2026: обычная строка",
     ["31.02.2026 12:00 · А: не дата\n12.10.2026: обычная строка"]),
])
def test_notes_are_ordered_as_complete_entries(source, expected):
    assert newest_first(source) == expected
