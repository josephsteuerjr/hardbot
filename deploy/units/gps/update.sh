#!/usr/bin/env bash
# ОБНОВЛЕНИЕ МАРШРУТОВ и применение правок .env:
#
#   cd deploy/units/gps && ./update.sh          # перезапуск на тех же образах
#   cd deploy/units/gps && ./update.sh --pull   # ещё и обновить образы OSRM/VROOM
#
# ПОЧЕМУ ПО УМОЛЧАНИЮ БЕЗ ОБНОВЛЕНИЯ ОБРАЗОВ. Здесь нечего собирать: образы
# готовые. Но дорожный граф собран КОНКРЕТНОЙ версией OSRM, и свежий образ
# может отказаться его читать — тогда придётся пересобирать граф (часы).
# Поэтому образы обновляются только по прямой просьбе: --pull.
#
# Данных у этой единицы нет: графы лежат в osrm/, скрипт их не трогает.
source "$(dirname "$0")/../../_lib.sh"
source "$DEPLOY_DIR/_actions.sh"

do_pull=0
case "${1:-}" in
  "") ;;
  --pull) do_pull=1 ;;
  *) die "неизвестный параметр «$1». Есть только один: --pull (обновить образы OSRM и VROOM)." ;;
esac

banner "обновление"
check_docker
require_env

if [ "$do_pull" = "1" ]; then
  step "1/3 Обновление образов"
  warn "после обновления образа OSRM граф может потребовать пересборки — это часы работы"
  hint "если маршруты после этого не поднимутся, соберите графы заново по $DEPLOY_DIR/geo/README.md"
  pull_images
else
  step "1/3 Образы"
  say "  оставляю те, что уже есть (обновить принудительно: ./update.sh --pull)"
fi

step "2/3 Перезапуск"
start_unit

step "3/3 Проверка"
if ! wait_unit; then
  die "маршрутизаторы не поднялись после обновления.
Что сделать по порядку:
  1) причина в журнале: docker compose logs --tail=50 <сервис>;
  2) если жалуется на файл графа — версия образа и графа разошлись: пересоберите граф по $DEPLOY_DIR/geo/README.md;
  3) ядро при этом работает: маршрут считается по прямой, никто ничего не теряет, кроме порядка объезда."
fi

say ""
say "==== Маршруты обновлены ===="
compose ps | sed 's/^/  /'
say ""
say "Если меняли состав стран — впишите их адреса в .env ядра и выполните там ./update.sh:"
for c in $(env_get COMPOSE_PROFILES | tr ',' ' '); do
  case "$c" in
    uz|tj|ru) say "  OSRM_URL_$(printf '%s' "$c" | tr '[:lower:]' '[:upper:]')=http://osrm-$c:5000" ;;
  esac
done
