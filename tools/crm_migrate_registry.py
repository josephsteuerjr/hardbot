"""Copy the existing registry transaction tables to PostgreSQL and verify their contents."""
import argparse
from contextlib import closing
import hashlib
import json
from pathlib import Path
import re
import sqlite3
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "server"))
from psycopg import sql
from psycopg.types.json import Jsonb
from crm.storage import Postgres

TABLES = (
    "clients", "calls", "visits", "payment_evidence", "registry_payments",
    "registry_monthly_totals", "enrichment_ledger", "enrichment_book_ledger",
    "enrichment_receipts", "employee_identities", "employee_aliases", "staff_roster",
    "client_extra", "assignment_events", "import_receipts", "import_source_heads", "audit", "settings",
)
TYPES = {"INTEGER": "bigint", "REAL": "double precision", "TEXT": 'text COLLATE "C"', "BLOB": "bytea"}
I = sql.Identifier


def columns(names):
    return sql.SQL(", ").join(map(I, names))


def table_columns(source, name):
    return list(source.execute('PRAGMA table_info("' + name + '")'))


def dataset(rows):
    h = hashlib.sha256()
    count = 0
    for row in rows:
        values = [bytes(v).hex() if isinstance(v, (bytes, memoryview)) else v for v in row]
        h.update(json.dumps(values, ensure_ascii=False, separators=(",", ":"), allow_nan=False).encode())
        h.update(b"\n")
        count += 1
    return {"rows": count, "sha256": h.hexdigest()}


def copy_table(source, target, name):
    fields = table_columns(source, name)
    if not fields:
        raise ValueError("Missing source table " + name)
    ddl = source.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (name,)).fetchone()[0]
    # These admitted tables have only ordinary keys and foreign keys. Other
    # constraints must be deliberately translated if a later primary adds them.
    if re.search(r"\b(CHECK|COLLATE|GENERATED)\b", ddl, re.I):
        raise ValueError("Unsupported source constraint on " + name)
    parts, identity = [], None
    key = [r["name"] for r in sorted(fields, key=lambda r: r["pk"]) if r["pk"]]
    for f in fields:
        # The primary stores both numeric account IDs and named system actors in audit.actor.
        kind = "jsonb" if (name, f["name"]) == ("audit", "actor") else TYPES[f["type"].upper()]
        if key == [f["name"]] and f["type"].upper() == "INTEGER":
            kind += " GENERATED BY DEFAULT AS IDENTITY"
            identity = f["name"]
        if f["notnull"]:
            kind += " NOT NULL"
        default = f["dflt_value"]
        if default is not None:
            if default.upper() == "CURRENT_TIMESTAMP" and f["type"].upper() == "TEXT":
                kind += " DEFAULT to_char(timezone('UTC', CURRENT_TIMESTAMP), 'YYYY-MM-DD HH24:MI:SS')"
            elif re.fullmatch(r"-?\d+|'(?:[^']|'')*'", default):
                kind += " DEFAULT " + default
            else:
                raise ValueError("Unsupported default on " + name + "." + f["name"])
        parts.append(sql.SQL("{} " + kind.replace("{", "{{").replace("}", "}}")).format(I(f["name"])))
    if not key:
        raise ValueError("Missing stable key on " + name)
    parts.append(sql.SQL("PRIMARY KEY ({})").format(columns(key)))
    indexes = []
    for idx in source.execute('PRAGMA index_list("' + name + '")'):
        if idx["origin"] == "pk":
            continue
        index_cols = [r["name"] for r in source.execute('PRAGMA index_info("' + idx["name"] + '")')]
        if idx["partial"] or None in index_cols:
            raise ValueError("Unsupported index on " + name)
        if idx["unique"]:
            parts.append(sql.SQL("UNIQUE ({})").format(columns(index_cols)))
        else:
            indexes.append(index_cols)
    for fk in source.execute('PRAGMA foreign_key_list("' + name + '")'):
        if fk["table"] not in TABLES or fk["seq"] or fk["on_update"] != "NO ACTION":
            raise ValueError("Unsupported reference on " + name)
        action = fk["on_delete"]
        if action not in {"NO ACTION", "CASCADE", "SET NULL", "RESTRICT"}:
            raise ValueError("Unsupported delete rule on " + name)
        parts.append(sql.SQL("FOREIGN KEY ({}) REFERENCES {} ({}) ON DELETE " + action).format(
            I(fk["from"]), I(fk["table"]), I(fk["to"])))
    target.raw.execute(sql.SQL("CREATE TABLE {} ({})").format(I(name), sql.SQL(", ").join(parts)))
    names = [f["name"] for f in fields]
    source_query = 'SELECT * FROM "' + name + '"'
    source_args = ()
    if name == "settings":
        from db import REGISTRY_COLUMN_MAP_SETTING
        source_query += " WHERE key=?"
        source_args = (REGISTRY_COLUMN_MAP_SETTING,)
    with target.raw.cursor().copy(sql.SQL("COPY {} ({}) FROM STDIN").format(I(name), columns(names))) as copy:
        for row in source.execute(source_query, source_args):
            if name == "audit":
                copy.write_row(tuple(Jsonb(v) if field == "actor" and v is not None else v
                                     for field, v in zip(names, row)))
            else:
                copy.write_row(tuple(row))
    for index_cols in indexes:
        target.raw.execute(sql.SQL("CREATE INDEX ON {} ({})").format(I(name), columns(index_cols)))
    if identity:
        highest = target.raw.execute(sql.SQL("SELECT max({}) FROM {}").format(I(identity), I(name))).fetchone()[0]
        target.execute("SELECT setval(pg_get_serial_sequence(?, ?), ?, ?)",
                       (name, identity, max(highest or 1, 1), bool(highest and highest >= 1)))
    order = ", ".join('"' + field + '"' for field in key)
    original = dataset(source.execute(source_query + " ORDER BY " + order, source_args))
    migrated = dataset(r.values() for r in target.raw.execute(sql.SQL("SELECT * FROM {} ORDER BY {}").format(I(name), columns(key))))
    if original != migrated:
        raise ValueError("Transferred rows differ on " + name)
    return original


def migrate(snapshot, dsn):
    with closing(sqlite3.connect(snapshot.resolve().as_uri() + "?mode=ro", uri=True)) as source, Postgres(dsn) as target:
        source.row_factory = sqlite3.Row
        source.execute("BEGIN")
        target.execute("SELECT pg_advisory_xact_lock(1836264771)")
        if target.execute("SELECT to_regnamespace('crm_registry')").fetchone()[0] is not None:
            raise ValueError("Registry schema already exists. The existing working data was preserved.")
        target.execute("CREATE SCHEMA crm_registry")
        target.execute("SET LOCAL search_path TO crm_registry, pg_catalog")
        result = {name: copy_table(source, target, name) for name in TABLES}
        target.execute("CREATE TABLE migration_receipt (singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton), active boolean NOT NULL DEFAULT false, snapshot jsonb NOT NULL, imported_at timestamptz NOT NULL DEFAULT now())")
        target.execute("INSERT INTO migration_receipt(snapshot) VALUES (?::jsonb)", (json.dumps(result),))
        target.execute("SET LOCAL search_path TO public, pg_catalog")
        target.execute(Path(__file__).with_name("crm_registry_permissions.sql").read_text(encoding="utf-8"))
        return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("snapshot", type=Path)
    parser.add_argument("--dsn-file", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(migrate(args.snapshot, args.dsn_file.read_text().strip())))
