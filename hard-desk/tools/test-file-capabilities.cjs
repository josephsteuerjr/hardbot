const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'hard-file-cap-'));
const compiled = path.join(root, 'caps.cjs');
require('esbuild').buildSync({entryPoints:[path.join(__dirname,'../src/main/file-capabilities.ts')],outfile:compiled,bundle:true,platform:'node',format:'cjs'});
const caps = require(compiled);
const selected = path.join(root, 'selected.jpg'), other = path.join(root, 'private.txt'), exe = path.join(root, 'program.exe');
for (const file of [selected,other,exe]) fs.writeFileSync(file,'synthetic');
assert.throws(()=>caps.selectedFile(1,other));
caps.grantFile(1, selected);
assert.equal(caps.uploadFile(1,selected),fs.realpathSync(selected));
assert.throws(()=>caps.selectedFile(2,selected));
assert.throws(()=>caps.selectedFile(1,other));
caps.grantFile(1,exe);
assert.throws(()=>caps.openFile(1,exe));
assert.throws(()=>caps.uploadFile(1,exe));
const folder=path.join(root,'portfolio'); fs.mkdirSync(folder);
const book=path.join(folder,'book.xlsx');fs.writeFileSync(book,'synthetic');
caps.grantFile(1,folder,false,true);
assert.equal(caps.selectedFile(1,book,true),fs.realpathSync(book));
assert.throws(()=>caps.selectedFile(1,path.join(folder,'..','private.txt'),true));
caps.clearFileGrants(1);
assert.throws(()=>caps.selectedFile(1,selected));
console.log('File capabilities: explicit selection, window ownership, safe types and directory boundary passed');
