#!/usr/bin/env bash
# УСТАНОВКА СЛУЖБЫ РЕЧИ одной командой:
#
#   cd deploy/units/stt && ./install.sh
#
# Это надстройка над ядром: без неё система работает полностью, сотрудники
# просто вводят текст руками. Ставить можно до ядра, после ядра или никогда —
# связь между ними держится не сетью, а общим томом, который создаётся сам.
#
# МОДЕЛЬ ЕДЕТ ВНУТРИ ОБРАЗА и ничего не качает. Раньше здесь было написано
# обратное («первый запуск скачивает модель, до 15 минут»), и это стоило дорого:
# когда служба не поднималась, инженер верил надписи и ждал скачивания, которого
# не было и быть не могло — в образе запрет на исходящий трафик. Правда простая:
# либо модель в образе есть и служба стартует за секунды, либо её там нет и
# ждать бесполезно, надо готовить модель и пересобирать образ.
source "$(dirname "$0")/../../_lib.sh"
source "$DEPLOY_DIR/_actions.sh"

banner "установка"
check_docker
ok "докер и compose v2 на месте"
require_sources stt
warn_if_low_disk 5

# --- 1. Настройки ------------------------------------------------------------
step "Настройки"
create_env
say "  модель: $(env_get STT_MODEL)  (сменить — поправить STT_MODEL в .env и ./update.sh, пересборка не нужна)"

# --- 2. Каталог модели -------------------------------------------------------
# Это НЕ то место, где лежит рабочая модель: она внутри образа. Каталог нужен
# двум редким случаям — сюда офлайн-пакет раскладывает привезённую модель, и
# сюда же качается модель, если её скачивание разрешили (STT_ALLOW_DOWNLOAD=1).
# В обычной установке он так и остаётся пустым, и это нормально.
step "Каталог модели"
mkdir -p models
ok "models/ на месте ($(human_size models))"

# --- 3. Образ и запуск -------------------------------------------------------
step "Образ"
build_images
step "Запуск"
# Токен доступа генерировать не нужно: его создаёт одноразовый контейнер
# stt-token ВНУТРИ общего тома, и делает это сам при каждом запуске, если
# токена ещё нет. Поэтому здесь нет ни файла секрета, ни его прав.
start_unit

# --- 4. Готовность -----------------------------------------------------------
step "Проверка"
say "Модель уже в образе, качать нечего: обычно готовность занимает секунды (ждём до $((UNIT_WAIT_SECONDS / 60)) мин)."
if ! wait_unit; then
  # ПРАВИЛО ЭТОГО СПИСКА: сначала смотрим В ЖУРНАЛ ВЫШЕ и ищем свою строку.
  # Прежний совет №1 звучал «подождите, модель скачивается в фоне» — это была
  # неправда при любом раскладе (в образе стоит запрет на исходящий трафик), и
  # она уводила от единственной строки, в которой написана настоящая причина.
  die "служба речи не поднялась.
Настоящая причина написана в строках журнала выше. Что там бывает:
  1) «в образе модели нет, а скачивание выключено» — образ собрали без весов.
     Подготовьте модель и пересоберите образ (нужен интернет на ЭТОЙ машине):
       python ../../../tools/prepare_stt_model.py && ./update.sh
     Нет интернета — возьмите готовый образ с машины, где он есть:
       там: docker save hard-stt -o hard-stt.tar   здесь: docker load -i hard-stt.tar && ./install.sh
  2) «файл токена» — удалите токен, он создастся заново сам:
       docker run --rm -v $SHARED_STT_VOLUME:/run/stt hard-stt rm -f /run/stt/stt.token && ./install.sh
  3) журнал обрывается без ошибки — почти всегда это нехватка памяти. Проверить:
       docker inspect --format '{{.State.OOMKilled}}' \$(docker compose ps -q stt)
     Лечится снятием лимита STT_MEM_LIMIT в .env (или моделью поменьше) и ./update.sh.
  4) в журнале нет ничего похожего — полная картина: $DEPLOY_DIR/doctor.sh
Ждать «пока докачается» бессмысленно: служба речи в интернет не ходит вообще."
fi
ok "модель загружена, распознавание отвечает"

# --- 5. Ядро -----------------------------------------------------------------
# Голос включается НЕ здесь, а в ядре одной строкой. Шаг маленький и потому
# легко забывается: тогда служба стоит и работает, а голосовые не распознаются
# и никто не понимает почему. Поэтому строку дописываем сами — но только если
# она пустая или выключена, и только строку: перезапуск ядра остаётся за человеком.
step "Связь с ядром"
core_env_file="$(core_env)"
if [ ! -f "$core_env_file" ]; then
  say "  ядро ещё не установлено — это нормально, порядок единиц не важен."
  say "  Когда поставите ядро, впишите в его .env строку VOICE_BACKEND=stt — и голос заработает."
else
  current="$(env_file_get "$core_env_file" VOICE_BACKEND)"
  case "$(printf '%s' "$current" | tr '[:upper:]' '[:lower:]')" in
    stt|praxis)
      ok "в ядре голос уже включён (VOICE_BACKEND=$current) — больше ничего делать не надо"
      say "  Ядро перечитывает токен на каждом запросе, поэтому перезапускать его не требуется." ;;
    ""|off)
      # Пусто или «off» — это заводское значение из .env.example, а не выбор
      # человека: ставить службу речи и оставлять голос выключенным незачем.
      env_file_set "$core_env_file" VOICE_BACKEND stt
      ok "в .env ядра вписано VOICE_BACKEND=stt (было: ${current:-пусто})"
      say ""
      say "  ОСТАЛСЯ ОДИН ШАГ — применить это в ядре:"
      say "      cd $(unit_dir core) && ./update.sh"
      say "  (не нужен голос — верните VOICE_BACKEND=off в $core_env_file)" ;;
    *)
      warn "в .env ядра стоит VOICE_BACKEND=$current — это не «stt», трогать не стал"
      hint "включить голос: впишите VOICE_BACKEND=stt в $core_env_file и выполните cd $(unit_dir core) && ./update.sh" ;;
  esac
fi

say ""
say "==== Служба речи установлена ===="
compose ps | sed 's/^/  /'
say ""
say "Полезное:"
say "  проверка:        ./doctor.sh"
say "  сменить модель:  STT_MODEL в .env, затем ./update.sh"
say "  сменить токен:   docker run --rm -v $SHARED_STT_VOLUME:/run/stt hard-stt rm -f /run/stt/stt.token && ./update.sh"
