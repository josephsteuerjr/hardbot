// Прелоад дизайн-студии: считает запросы в полёте, чтобы снимок снимался,
// когда экран дорисован, а не по угаданной паузе. contextIsolation выключен
// только в студии — страница своя, с дев-стенда.
(() => {
  let n = 0;
  window.__studioInflight = () => n;
  const f = window.fetch.bind(window);
  window.fetch = (...a) => { n++; return f(...a).finally(() => { n--; }); };
  // Системные вопросы остановили бы прогон: в студии «да» отвечаем сами.
  window.confirm = () => true;
  window.alert = () => {};
})();
