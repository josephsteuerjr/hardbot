# Длинные ключи матчим раньше коротких («петербург» не должен съесть «санкт-петербург»)
_KEYS = sorted(CENTROIDS.items(), key=lambda kv: -len(kv[0]))


def _norm(s: str | None) -> str:
    return (s or "").strip().lower().replace("ё", "е")


# --- Интерфейс скоринга / anchor-guard ---------------------------------------
def parse_city(address, city_col):
    """Достать курируемый город Согда из (Город · Адрес). → (display, lat, lon) | (None,…)."""
    text = f"{city_col or ''} {address or ''}".lower()
    for tokens, disp, lat, lon in SUGHD:
        if any(t in text for t in tokens):
            return disp, lat, lon
    return None, None, None


def sughd_centroid(name: str) -> tuple[float, float] | None:
    """Координаты курируемого города по его display-имени (для списка кластеров)."""
    for _toks, disp, lat, lon in SUGHD:
        if disp == name:
            return lat, lon
    return None


# --- Широкий офлайн-интерфейс (движок) ---------------------------------------
def lookup(city: str | None, address: str | None) -> tuple[float, float, str] | None:
    """Вернуть (lat, lon, matched_key) по широкому справочнику или None. Офлайн."""
    text = f"{_norm(city)} {_norm(address)}"
    for key, (lat, lon) in _KEYS:
        if key in text:
            return lat, lon, key
    return None


def jitter(lat: float, lon: float, seed: str, radius_deg: float = 0.018) -> tuple[float, float]:
    """Детерминированный сдвиг ~±2 км по ключу (seed), чтобы точки города не слипались."""
    h = int(hashlib.md5((seed or "").encode()).hexdigest(), 16)
    dlat = ((h % 1000) / 1000 - 0.5) * 2 * radius_deg
    dlon = ((h // 1000 % 1000) / 1000 - 0.5) * 2 * radius_deg
    return round(lat + dlat, 6), round(lon + dlon, 6)


def geocode_jittered(city, address, seed) -> tuple[float, float, str] | None:
    g = lookup(city, address)
    if not g:
        return None
    lat, lon = jitter(g[0], g[1], seed)
    return lat, lon, g[2]
