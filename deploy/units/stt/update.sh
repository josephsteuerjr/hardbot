#!/usr/bin/env bash
# ОБНОВЛЕНИЕ СЛУЖБЫ РЕЧИ и применение правок её .env:
#
#   cd deploy/units/stt && ./update.sh
#
# Данных у этой единицы нет — есть только скачанная модель в models/, и она
# при обновлении не трогается. Поэтому резервных копий тут не бывает: если
# что-то пойдёт не так, единицу просто ставят заново.
#
# Смена модели (STT_MODEL) — это НЕ просто ./update.sh. Модель едет внутри
# образа, качать её служба не станет: поменяли имя — сначала подготовьте новую
# модель (tools/prepare_stt_model.py --name <модель>), и только потом ./update.sh,
# который пересоберёт образ. Иначе служба честно возьмёт запечённую модель
# вместо запрошенной и напишет об этом в журнал при каждом старте.
source "$(dirname "$0")/../../_lib.sh"
source "$DEPLOY_DIR/_actions.sh"

banner "обновление"
check_docker
require_env

step "1/3 Сборка образа"
build_images

step "2/3 Перезапуск"
start_unit

step "3/3 Проверка"
say "Модель в образе, качать нечего: обычно готовность занимает секунды (ждём до $((UNIT_WAIT_SECONDS / 60)) мин)."
if ! wait_unit; then
  die "служба речи не поднялась после обновления.
Настоящая причина — в строках журнала выше. Что там бывает:
  1) «в образе модели нет» или «беру модель, запечённую в образ» — в .env стоит
     STT_MODEL, которой в образе нет. Либо верните имя запечённой модели, либо
     подготовьте нужную и пересоберите:
       python ../../../tools/prepare_stt_model.py --name <модель> && ./update.sh
  2) журнал обрывается без ошибки — почти всегда нехватка памяти: снимите лимит
     STT_MEM_LIMIT в .env (или возьмите модель поменьше) и повторите ./update.sh;
  3) ядро при этом работает: голос временно недоступен, сотрудники вводят текст руками.
Ждать «пока докачается» бессмысленно: служба речи в интернет не ходит вообще."
fi

docker image prune -f --filter "label=ru.hard.service" >/dev/null 2>&1 || true

say ""
say "==== Служба речи обновлена ===="
compose ps | sed 's/^/  /'
say "  модель: $(env_get STT_MODEL), каталог models/ занимает $(human_size models)"
