"""Пульт руководителя направления — отдельное приложение, не раздел пульта аналитика.

Почему отдельное и почему веб. Руководитель открывает пульт на две минуты между
совещаниями и половину этих минут — с телефона. Окно на Qt в тоннель не пролезает,
поэтому здесь местный веб-сервер на 127.0.0.1 и браузер поверх него: одна и та же
страница открывается и на ПК, и на телефоне через cloudflared.

Что где лежит:

* `settings.py` — адрес «Харда» и токен доступа. Токен не покидает ПК: ни в
  адресах, ни в отдаваемом наружу JSON его нет.
* `hard.py` — клиент сервера «Хард». Ходит в `/api/manager/*`, обменивает ссылку
  входа на токен и на каждую беду отдаёт человеку русскую строку, а не код.
* `session.py` — кто стучится: свой браузер с этого же ПК или телефон из тоннеля.
  Телефон обязан один раз ввести четырёхзначный код-пропуск.
* `tunnel.py` — быстрый тоннель cloudflared: поднять, выцарапать адрес, погасить.
* `server.py` — местный API и раздача `web/`.
* `web/` — страница (её пишет и ведёт автор интерфейса, здесь она только раздаётся).

Запуск: «Пульт руководителя.pyw» в корне проекта или `python -m pult_ruk`.
"""

__all__ = ["settings", "hard", "session", "tunnel", "server"]
