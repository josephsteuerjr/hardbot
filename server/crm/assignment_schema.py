"""Additive distribution model; operational enablement is deliberately explicit."""

DDL = """
CREATE INDEX IF NOT EXISTS crm_assignment_slot ON crm_assignments(contract_uuid,capability,ends_at,employee_uuid);
CREATE TABLE IF NOT EXISTS crm_managed_contracts(
 team_id TEXT NOT NULL, contract_uuid TEXT NOT NULL REFERENCES crm_contracts,
 capability TEXT NOT NULL CHECK(capability IN ('call','visit')),
 PRIMARY KEY(team_id,contract_uuid,capability));
CREATE INDEX IF NOT EXISTS crm_managed_contract ON crm_managed_contracts(contract_uuid,capability);
CREATE TABLE IF NOT EXISTS crm_distribution_managers(
 employee_uuid TEXT NOT NULL REFERENCES crm_employees, team_id TEXT NOT NULL,
 capability TEXT NOT NULL CHECK(capability IN ('call','visit')),
 PRIMARY KEY(employee_uuid,team_id,capability));
CREATE TABLE IF NOT EXISTS crm_assignment_heads(
 contract_uuid TEXT NOT NULL REFERENCES crm_contracts,
 capability TEXT NOT NULL CHECK(capability IN ('call','visit')),
 employee_uuid TEXT REFERENCES crm_employees, revision BIGINT NOT NULL,
 updated_at TEXT NOT NULL, operation_id TEXT NOT NULL, source TEXT NOT NULL,
 baseline_employee_uuid TEXT REFERENCES crm_employees,
 PRIMARY KEY(contract_uuid,capability));
CREATE INDEX IF NOT EXISTS crm_head_employee ON crm_assignment_heads(employee_uuid,capability,contract_uuid);
CREATE TABLE IF NOT EXISTS crm_assignment_operations(
 actor_uid BIGINT NOT NULL, operation_id TEXT NOT NULL, request_hash TEXT NOT NULL,
 result_json TEXT NOT NULL, received_at TEXT NOT NULL,
 PRIMARY KEY(actor_uid,operation_id));
CREATE TABLE IF NOT EXISTS crm_assignment_previews(
 preview_id TEXT PRIMARY KEY, actor_uid BIGINT NOT NULL,
 body_json TEXT NOT NULL, created_at TEXT NOT NULL, expires_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS crm_assignment_changes(
 sequence INTEGER PRIMARY KEY AUTOINCREMENT,
 actor_uid BIGINT NOT NULL, operation_id TEXT NOT NULL, team_id TEXT NOT NULL,
 contract_uuid TEXT NOT NULL REFERENCES crm_contracts, capability TEXT NOT NULL,
 before_employee_uuid TEXT, after_employee_uuid TEXT,
 revision BIGINT NOT NULL, at TEXT NOT NULL, source TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS crm_assignment_change_contract ON crm_assignment_changes(contract_uuid,sequence);
CREATE TABLE IF NOT EXISTS crm_task_grant_revocations(
 entity_id TEXT NOT NULL REFERENCES crm_entities, capability TEXT NOT NULL,
 operation_id TEXT NOT NULL, revoked_at TEXT NOT NULL,
 PRIMARY KEY(entity_id,capability));
CREATE VIEW IF NOT EXISTS crm_effective_assignments AS
 SELECT ('head:' || h.contract_uuid || ':' || h.capability) AS assignment_id,
 h.employee_uuid,h.contract_uuid,h.capability,h.updated_at AS starts_at,
 NULL AS ends_at,h.source
 FROM crm_assignment_heads h WHERE h.employee_uuid IS NOT NULL
 UNION ALL
 SELECT a.assignment_id,a.employee_uuid,a.contract_uuid,a.capability,a.starts_at,a.ends_at,a.source
 FROM crm_assignments a
 WHERE NOT EXISTS(SELECT 1 FROM crm_assignment_heads h
   WHERE h.contract_uuid=a.contract_uuid AND h.capability=a.capability)
 AND NOT EXISTS(SELECT 1 FROM crm_assignments b WHERE b.contract_uuid=a.contract_uuid
   AND b.capability=a.capability AND b.ends_at IS NULL AND a.ends_at IS NULL
   AND b.employee_uuid<>a.employee_uuid);
"""


def ddl(postgres=False):
    return DDL.replace('sequence INTEGER PRIMARY KEY AUTOINCREMENT',
                       'sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').replace(
                       'CREATE VIEW IF NOT EXISTS','CREATE OR REPLACE VIEW') if postgres else DDL
